// на русском и английским языках только». Остальные восемь языков страницы
// получают английский — деградация к `en` тут честнее пустоты и честнее
// машинного перевода, которого никто не читал.
//
// 🔒 ТЕКСТ РАЗРЕЗАН НА ТРИ ЧАСТИ, А НЕ СОБРАН КОНКАТЕНАЦИЕЙ В РАЗМЕТКЕ: ссылка
// стоит В СЕРЕДИНЕ фразы, и у языков порядок слов разный. Склейка «начало + <a> +
// конец» прямо в JSX однажды выдаёт фразу задом наперёд на языке, который никто
// не проверял.
//
// 🔒 ДВА НАБОРА СЛОВ НА ОДИН ВИД — решение владельца 2026-09-20. Оформление
// полосы он назвал идеальным и велел применить его ко второму случаю: «этот
// нотификейшн должен остаться во всех служебных страницах, но там у нас есть
// Notification и он уродливый… используй этот макет, но оставь там утверждённый
// текст». Отсюда две функции: вид один, поводы разные.

export type StarterBannerStrings = {
  /** Что человек сейчас видит. */
  lead: string
  /** Подпись ссылки. */
  linkLabel: string
  /** Хвост фразы после ссылки; может быть пустым. */
  tail: string
}

// 706-3: повод первый («сайт ещё не ваш», полоса на всех страницах) снят — его место заняла полоса быстрой навигации
// (`quick-nav.client.tsx`), которую видит только владелец.

// ── Повод второй: у страницы ещё нет текста ─────────────────────────────────
//
// 🪦 ЭТИ СЛОВА ПЕРЕЕХАЛИ ИЗ `lib/pages/notice.i18n.ts`, где рисовались серой
// курсивной строкой посреди готовой страницы. Смысл сохранён — владелец назвал
// идею правильной, — а вид заменён на тот, что он утвердил.
const EN_PAGE_TEXT: StarterBannerStrings = {
  lead: 'This page has no text of its own yet. It works and it is indexed — it is simply a template:',
  linkLabel: 'start the project',
  tail: '',
}

const RU_PAGE_TEXT: StarterBannerStrings = {
  lead: 'У этой страницы пока нет собственного текста. Она работает и индексируется — это рабочий шаблон:',
  linkLabel: 'запуск проекта',
  tail: '',
}

/** Слова для повода «у страницы ещё нет текста» — врезка служебных страниц. */
export function pageTextBannerStrings(lang: string): StarterBannerStrings {
  return lang === 'ru' ? RU_PAGE_TEXT : EN_PAGE_TEXT
}
